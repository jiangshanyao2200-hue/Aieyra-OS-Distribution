'use strict';
// JSON is authoritative; the renderer receives a generated script module so it
// does not need connect-src access to load an import-attribute JSON resource.
const fs=require('node:fs'),path=require('node:path');
const dir=path.resolve(__dirname,'../../Theme/contract'),file=path.join(dir,'elements.mjs'),schemaFile=path.resolve(dir,'../../Contracts/theme.schema.json');
const catalog=JSON.parse(fs.readFileSync(path.join(dir,'elements.json'),'utf8'));
const expected='// Generated by SDK/tools/theme-catalog.cjs from elements.json.\nexport default '+JSON.stringify(catalog,null,2)+';\n';
// Editor validation and runtime admission share the same element/surface
// vocabulary. Keep the handwritten structural schema and derive its enums.
function authorSchema(){
 const schema=JSON.parse(fs.readFileSync(schemaFile,'utf8'));
 schema.properties.elements.const=catalog.version;
 schema.properties.sounds.propertyNames.enum=require('../../Theme/contract/assets.mjs').soundEvents;
 schema.properties.styles.items.properties.element.enum=Object.keys(catalog.elements);
 schema.properties.styles.items.properties.state.enum=Object.keys(catalog.states);
 schema.properties.layouts.propertyNames.enum=Object.keys(catalog.surfaces);
 schema.properties.renderers.propertyNames.enum=Object.keys(catalog.renderers);
 schema.$defs.properties.propertyNames.enum=catalog.properties;
 return JSON.stringify(schema,null,2)+'\n';
}
function sync(check=false){
 for(const [target,value]of [[file,expected],[schemaFile,authorSchema()]]){
  if(check){if(!fs.existsSync(target)||fs.readFileSync(target,'utf8')!==value)throw Error('Theme generated contract is stale: '+path.basename(target)+'; run SDK/tools/theme-catalog.cjs');}
  else fs.writeFileSync(target,value);
 }
}
if(require.main===module)sync(process.argv.includes('--check'));
module.exports={sync};
