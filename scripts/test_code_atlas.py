"""Exercise navigation drift and protected-byte boundaries in synthetic trees."""
import importlib.util
import json
from pathlib import Path
import tempfile
import unittest

spec = importlib.util.spec_from_file_location('code_atlas',Path(__file__).with_name('code-atlas.py'))
atlas = importlib.util.module_from_spec(spec)
spec.loader.exec_module(atlas)


class CodeAtlasTests(unittest.TestCase):
    def project(self, root):
        def put(name, value):
            p = root/name
            p.parent.mkdir(parents=True,exist_ok=True)
            p.write_text(value,encoding='utf-8')
        put('docs/工程地图.json',json.dumps({'modules':[{'id':'app','path':'App','agreement':'App/AGENTS.md'}]}))
        put('App/AGENTS.md','# owner\n')
        put('Contracts/code-chains.json',json.dumps({'schema':'aieyra.code-chains/1','rings':{'1':{'modules':['app']}},'chains':[{'id':'app','purpose':'fixture','files':['App/main.mjs'],'invariants':['one service'],'scenes':[]}]}))
        put('Contracts/development-documents.json',json.dumps({'documents':['App/AGENTS.md']}))
        put('Contracts/desktop-compatibility.json',json.dumps({'files':{}}))
        put('App/main.mjs',"'use strict';\nimport {value} from './value.mjs';\nexport function main(){return value;}\n")
        put('App/value.mjs','export const value=1;\n')
        put('App/skin.css','@charset "UTF-8";\n:root{--color:white}\n')
        put('App/tool.py','#!/usr/bin/env python3\n# coding: utf-8\n"""doc"""\nfrom __future__ import annotations\ndef run(): return 1\n')
        put('App/package/manifest.json','{}\n')
        put('App/package/start.mjs','export const fixed=1;\n')
        put('App/data/private.py','not valid Python and must never be read\n')

    def test_refresh_is_idempotent_and_preserves_package_and_preambles(self):
        with tempfile.TemporaryDirectory() as task_dir:
            root=Path(task_dir)
            self.project(root)
            first,outputs=atlas.build(root)
            protected=(root/'App/package/start.mjs').read_bytes()
            originals={n:(root/n).read_text(encoding='utf-8') for n in first['files']}
            atlas.refresh(root,outputs,first)
            second,again=atlas.build(root)
            self.assertEqual(first,second)
            self.assertTrue(atlas.check(root,second,again)['ok'])
            self.assertEqual(protected,(root/'App/package/start.mjs').read_bytes())
            self.assertNotIn('App/package/CODEMAP.md',outputs)
            self.assertNotIn('App/data/private.py',first['files'])
            for name,before in originals.items():
                self.assertEqual(before,atlas.without_header((root/name).read_text(encoding='utf-8'),name))
            self.assertTrue((root/'App/skin.css').read_text().startswith('@charset "UTF-8";'))
            self.assertTrue((root/'App/tool.py').read_text().startswith('#!/usr/bin/env python3\n# coding: utf-8'))
            compile((root/'App/tool.py').read_text(), 'tool.py', 'exec')

    def test_modified_new_and_deleted_code_invalidates_navigation(self):
        with tempfile.TemporaryDirectory() as task_dir:
            root=Path(task_dir)
            self.project(root)
            before,outputs=atlas.build(root)
            atlas.refresh(root,outputs,before)
            (root/'App/new.mjs').write_text('export function newEntry(){}\n')
            (root/'App/value.mjs').write_text('export const replacement=2;\n')
            after,expected=atlas.build(root)
            self.assertFalse(atlas.check(root,after,expected)['ok'])
            self.assertIn('replacement',[r['name'] for r in after['files']['App/value.mjs']['regions']])
            atlas.refresh(root,expected,after)
            (root/'App/new.mjs').unlink()
            after,expected=atlas.build(root)
            self.assertFalse(atlas.check(root,after,expected)['ok'])

    def test_generated_by_and_from_keep_exact_generator_bytes_after_refresh(self):
        with tempfile.TemporaryDirectory() as task_dir:
            root = Path(task_dir)
            self.project(root)
            originals = {
                'App/catalog.mjs': b'// Generated by SDK/catalog.cjs from catalog.json.\nexport default {};\n',
                'App/schema.py': b'# Generated from schema.json\nSCHEMA = {}\n',
                'App/palette.css': b'/* Generated by palette.cjs */\n:root{--accent:#fff}\n',
            }
            for name, value in originals.items():
                (root/name).write_bytes(value)
            for _ in range(2):
                index, outputs = atlas.build(root)
                atlas.refresh(root, outputs, index)
                for name, value in originals.items():
                    self.assertEqual(index['files'][name]['protected'], 'generated')
                    self.assertEqual((root/name).read_bytes(), value)
                    self.assertNotIn(name, outputs)
                self.assertTrue(atlas.check(root, index, outputs)['ok'])

    def test_import_impact_and_unknown_chain_path_are_not_fabricated(self):
        with tempfile.TemporaryDirectory() as task_dir:
            root=Path(task_dir)
            self.project(root)
            doc,_=atlas.build(root)
            self.assertEqual(['App/value.mjs'],doc['files']['App/main.mjs']['imports'])
            self.assertEqual(['App/main.mjs'],doc['files']['App/value.mjs']['consumers'])
            (root/'App/main.mjs').unlink()
            with self.assertRaisesRegex(ValueError,'Chain entry missing'):
                atlas.build(root)

    def test_context_tracks_consumers_real_lines_ancestor_rules_and_omissions(self):
        with tempfile.TemporaryDirectory() as task_dir:
            root = Path(task_dir)
            self.project(root)
            (root/'AGENTS.md').write_text('# root instructions\n',encoding='utf-8')
            (root/'App/nested').mkdir()
            (root/'App/nested/AGENTS.md').write_text('# nested instructions\n',encoding='utf-8')
            (root/'App/nested/use.mjs').write_text("import {value} from '../value.mjs';\nexport function use(){return value;}\n",encoding='utf-8')
            index, outputs = atlas.build(root)
            atlas.refresh(root, outputs, index)
            packet = atlas.context_packet(root, 'App/value.mjs', limit=2)
            self.assertEqual(3, packet['discoveredFiles'])
            self.assertEqual(1, packet['omittedFiles'])
            self.assertEqual('consumer', packet['files'][1]['why']['relation'])
            full = atlas.context_packet(root, 'App/value.mjs')
            nested = next(r for r in full['files'] if r['file']=='App/nested/use.mjs')
            self.assertEqual(['AGENTS.md','App/AGENTS.md','App/nested/AGENTS.md'],nested['agreements'])
            for region in nested['regions']:
                actual = (root/nested['file']).read_text(encoding='utf-8').splitlines()[region['line']-1]
                self.assertIn(region['name'],actual)
            self.assertTrue(atlas.validate_context(root, full)['ok'])
            self.assertNotIn('private.py',json.dumps(full))

    def test_context_rejects_other_file_changes_new_consumers_and_changed_instructions(self):
        with tempfile.TemporaryDirectory() as task_dir:
            root = Path(task_dir)
            self.project(root)
            index, outputs = atlas.build(root)
            atlas.refresh(root, outputs, index)
            packet = atlas.context_packet(root, 'App/value.mjs')
            rule = root/'App/AGENTS.md'
            rule.write_text('# revised instructions\n',encoding='utf-8')
            with self.assertRaisesRegex(ValueError,'stale or modified'):
                atlas.validate_context(root,packet)
            rule.write_text('# owner\n',encoding='utf-8')
            (root/'App/new-consumer.mjs').write_text("import './value.mjs';\n",encoding='utf-8')
            with self.assertRaisesRegex(ValueError,'inventory changed'):
                atlas.validate_context(root,packet)
            (root/'App/new-consumer.mjs').unlink()
            (root/'App/skin.css').write_text(':root{--color:red}\n',encoding='utf-8')
            with self.assertRaisesRegex(ValueError,'body changed'):
                atlas.context_packet(root,'App/value.mjs')

    def test_context_refuses_tampered_constraints_wrong_root_and_incomplete_seed_set(self):
        with tempfile.TemporaryDirectory() as task_dir:
            root = Path(task_dir)
            self.project(root)
            config = atlas.load(root,'Contracts/code-chains.json')
            config['chains'][0]['files'].append('App/value.mjs')
            (root/'Contracts/code-chains.json').write_text(json.dumps(config),encoding='utf-8')
            index, outputs = atlas.build(root)
            atlas.refresh(root, outputs, index)
            with self.assertRaisesRegex(ValueError,'retain all chain seeds'):
                atlas.context_packet(root,'chain:app',limit=1)
            packet = atlas.context_packet(root,'chain:app')
            packet['chains'][0]['invariants'] = []
            with self.assertRaisesRegex(ValueError,'stale or modified'):
                atlas.validate_context(root,packet)
            packet['sourceRoot'] = str(root/'different')
            with self.assertRaisesRegex(ValueError,'different source root'):
                atlas.validate_context(root,packet)
            for malformed in (None, [], 'not a packet', {}):
                with self.assertRaises(ValueError):
                    atlas.validate_context(root,malformed)

    def test_escape_and_symlink_are_rejected(self):
        with tempfile.TemporaryDirectory() as task_dir:
            root=Path(task_dir)
            for name in ('../outside','App/../../outside','C:/untrusted/outside','/absolute','App\\x'):
                with self.assertRaises(ValueError):
                    atlas.safe(root,name)
            try:
                (root/'linked').symlink_to(root,target_is_directory=True)
            except OSError:
                return
            with self.assertRaises(ValueError):
                atlas.safe(root,'linked/code.py')

    def test_concurrent_source_edits_stop_refresh_and_interrupted_writes_are_retained(self):
        with tempfile.TemporaryDirectory() as task_dir:
            root=Path(task_dir)
            self.project(root)
            before,outputs=atlas.build(root)
            (root/'App/main.mjs').write_text('export const humanEdit=1;\n')
            with self.assertRaisesRegex(ValueError,'Source changed'):
                atlas.refresh(root,outputs,before)
            self.assertIn('humanEdit',(root/'App/main.mjs').read_text())
            target=root/'retained.txt'
            target.write_bytes(b'original')
            temporary=root/'retained.txt.code-atlas.tmp'
            temporary.write_bytes(b'interrupted')
            with self.assertRaisesRegex(ValueError,'interrupted write retained'):
                atlas.atomic_write(target,b'new')
            self.assertEqual(b'original',target.read_bytes())
            self.assertEqual(b'interrupted',temporary.read_bytes())


if __name__=='__main__':
    unittest.main()
